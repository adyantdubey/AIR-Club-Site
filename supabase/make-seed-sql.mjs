// Builds supabase/seed_content.sql from client/src/data/oldSite.js.
// Run from the project folder:   node supabase/make-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CLUB, FACULTY, TEAM, OLD_PROJECTS, OLD_EVENTS, VIDEOS, drive } from '../client/src/data/oldSite.js';

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const out = [];
out.push(`-- =====================================================================
--  The club's real content (team, faculty, earlier projects, past events,
--  Learn videos, contact details) for Supabase.
--
--  Run ONCE, after database_schema.sql:  SQL Editor → New query → paste → Run.
--  Safe to run again: rows that already exist are left as they are.
--  Generated by supabase/make-seed-sql.mjs — edit client/src/data/oldSite.js, not this file.
-- =====================================================================
`);

out.push('-- club details');
out.push(
  `update public.site_settings set ${['club_name', 'tagline', 'email', 'phone', 'address', 'linkedin', 'instagram', 'youtube', 'mission'].map((k) => `${k} = ${q(CLUB[k])}`).join(',\n  ')}\nwhere id = 1;\n`,
);

out.push('-- team and faculty coordinator');
const people = [
  ...TEAM.map((m, i) => ({ id: `tm-${i}`, ...m, department: null, bio: null, email: null })),
  ...FACULTY.map((f, i) => ({ id: `tm-f${i}`, name: f.name, role: f.role, group: 'faculty', department: f.department, bio: f.bio, photo_url: f.photo_url, email: f.email, linkedin: null, is_lead: false, sort_order: 100 + i })),
];
out.push(
  `insert into public.team_members (id, name, role, "group", department, bio, photo_url, email, linkedin, is_lead, sort_order) values\n` +
    people.map((m) => `  (${[m.id, m.name, m.role, m.group, m.department, m.bio, m.photo_url, m.email, m.linkedin, m.is_lead, m.sort_order].map(q).join(', ')})`).join(',\n') +
    `\non conflict (id) do nothing;\n`,
);

out.push('-- earlier projects');
out.push(
  `insert into public.projects (id, slug, title, summary, description, body, category, status, progress, team_size, tech, archived, image_url, image2_url) values\n` +
    OLD_PROJECTS.map((p) => `  (${[p.slug, p.slug, p.title, p.summary, p.summary, p.body, p.category, p.status].map(q).join(', ')}, ${q(p.progress)}, null, ${arr(p.tech)}, true, ${q(drive(p.image))}, ${q(drive(p.image2))})`).join(',\n') +
    `\non conflict (id) do nothing;\n`,
);

out.push('-- past events');
out.push(
  `insert into public.events (id, title, kind, starts_at, ends_at, venue, description, body, registration_open, capacity, image_url, image2_url, link) values\n` +
    OLD_EVENTS.map((e) => `  (${[e.id, e.title, e.kind, e.starts_at, e.ends_at, e.venue, e.summary, e.body].map(q).join(', ')}, false, ${q(e.capacity)}, ${q(drive(e.image))}, ${q(drive(e.image2))}, ${q(e.link)})`).join(',\n') +
    `\non conflict (id) do nothing;\n`,
);

out.push('-- Learn page videos');
out.push(
  `insert into public.resources (id, title, url, kind, sort_order) values\n` +
    VIDEOS.map(([kind, title, yt], i) => `  (${[`rs-${i + 1}`, title, `https://www.youtube.com/watch?v=${yt}`, kind, i].map(q).join(', ')})`).join(',\n') +
    `\non conflict (id) do nothing;\n`,
);

const file = fileURLToPath(new URL('./seed_content.sql', import.meta.url));
writeFileSync(file, out.join('\n'));
console.log(`wrote ${file}: ${people.length} people, ${OLD_PROJECTS.length} projects, ${OLD_EVENTS.length} events, ${VIDEOS.length} videos`);
